"""Write docs/FINAL_RATIOS.md: every harmonization factor per region, frozen for release v1.0-data.

Reads the exported meta.json files (the values the frontend and the teammate backend serve) and
config.yaml (fit years, bootstrap settings), so the document cannot drift from the published data.

    .venv/bin/python tools/final_ratios.py
"""

import json
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "src"))

from firecal.config import load_config  # noqa: E402

REGIONS = ["lebanon", "greece", "eastmed"]
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def yr(span) -> str:
    return f"{span[0]}–{span[1]}"


def band(lo, hi) -> str:
    return f"[{lo:.4f}, {hi:.4f}]"


def same_for_all_months(rows, key) -> bool:
    return len({r[key] for r in rows}) == 1


def factor_table(rows, key, extra=()) -> list[str]:
    """One row per calendar month: value and 90% band (plus intercept columns when present)."""
    head = ["month", key, "90% band", *[h for h, _ in extra]]
    out = ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)]
    for r in rows:
        cells = [MONTHS[r["month"] - 1], f"{r[key]:.4f}", band(r[f"{key}_low"], r[f"{key}_high"])]
        cells += [fn(r) for _, fn in extra]
        out.append("| " + " | ".join(cells) + " |")
    return out


def main() -> None:
    cfg = load_config()
    boot = cfg["calibration"]["bootstrap"]
    terra_fit = cfg["terra"]["fit_years"]
    cont_cfg = cfg["continuation"]
    head = subprocess.run(["git", "rev-parse", "--short", "HEAD"], cwd=ROOT, capture_output=True, text=True).stdout.strip()

    metas = {r: json.loads((ROOT / f"data/export/{r}/meta.json").read_text()) for r in REGIONS}
    L = [
        "# Final harmonization ratios (v1.0-data)",
        "",
        "Frozen factors behind the exported harmonized series. Generated by `tools/final_ratios.py` from",
        "`data/export/{region}/meta.json` (data contract "
        + ", ".join(sorted({m["contract_version"] for m in metas.values()}))
        + ") and `config.yaml`; do not edit by hand.",
        "",
        "## How the factors are used",
        "- **a_m (MODIS → VIIRS S-NPP), and b_m when affine:** before 2012-01-20,",
        "  harmonized = a_m · kT(m)^[Terra-only] · MODIS fire-days (+ b_m spread over cells for affine strategies).",
        "- **kT(m) (Terra-only correction):** applied to MODIS segments before 2002-07-04 (Aqua start),",
        "  kT = Σ N_Terra∪Aqua / Σ N_Terra.",
        "- **c_m (NOAA-20 → S-NPP):** from 2026-11-03 (S-NPP's last data 2026-11-02),",
        "  harmonized = c_m · NOAA-20 fire-days.",
        "- From 2012-01-20 to 2026-11-02, harmonized is observed VIIRS S-NPP. No factor is applied.",
        f"- **Bands:** 90% from a year bootstrap, B = {boot['n']}, seed {boot['seed']}, resampling fit years with",
        "  replacement. kT and a_m are drawn independently.",
        "- **Fitting:** persistent industrial/waste-burning fire-days excluded; days with a flagged outage, or",
        "  without data from every involved satellite, are excluded.",
        "",
        "## Summary",
        "",
        "| region | MODIS→VIIRS strategy | a fit years | kT strategy | kT fit years | NOAA-20 strategy | c fit years | config hash | generated |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for r, m in metas.items():
        c = m["calibration"]
        L.append(
            f"| {r} | `{c['strategy']}` | {yr(c['overlap_years'])} | `{c['terra_strategy']}` | {yr(terra_fit)} | "
            f"`{c['continuation']['strategy']}` | {yr(c['continuation']['overlap_years'])} | "
            f"`{m['pipeline']['config_hash']}` | {m['generated_at']} |"
        )

    for r, m in metas.items():
        c = m["calibration"]
        L += ["", f"## {r.capitalize()}", ""]

        L += [f"### MODIS → VIIRS: a_m (strategy `{c['strategy']}`, fit {yr(c['overlap_years'])})", ""]
        comp = c.get("composite") or {}
        if comp:
            L += [
                f"Composite: each year's estimated total comes from the **level** model (`{comp['level']['strategy']}`) and",
                f"the monthly shape from the **shape** model (`{comp['shape']['strategy']}`, k = {comp['shape'].get('k')}).",
                f"Bands: {comp.get('bands', '')}.",
                "",
            ]
        if same_for_all_months(c["factors"], "a") and not any(f["b"] for f in c["factors"]):
            f = c["factors"][0]
            L += [f"Level model: one ratio for every month, **a = {f['a']:.4f}**, 90% band {band(f['a_low'], f['a_high'])}, b = 0."]
        else:
            affine = any(f["b"] for f in c["factors"])
            L += factor_table(c["factors"], "a", extra=[("b", lambda f: f"{f['b']:.4f}")] if affine else ())
        if comp:
            L += ["", f"Shape model `{comp['shape']['strategy']}` (affine, a·MODIS + b fire-days per month):", ""]
            L += factor_table(
                comp["shape"]["factors"], "a",
                extra=[("b", lambda f: f"{f['b']:.4f}"), ("b 90% band", lambda f: band(f["b_low"], f["b_high"]))],
            )

        L += ["", f"### Terra-only correction: kT(m) (strategy `{c['terra_strategy']}`, fit {yr(terra_fit)})", ""]
        t = c["terra_correction"]
        if same_for_all_months(t, "kT"):
            L += [f"One factor for every month: **kT = {t[0]['kT']:.4f}**, 90% band {band(t[0]['kT_low'], t[0]['kT_high'])}."]
        else:
            L += factor_table(t, "kT")

        k = c["continuation"]
        L += ["", f"### NOAA-20 → S-NPP: c_m (strategy `{k['strategy']}`, fit {yr(k['overlap_years'])}, switch {k['switch_date']})", ""]
        if same_for_all_months(k["factors"], "c"):
            f = k["factors"][0]
            L += [f"One factor for every month: **c = {f['c']:.4f}**, 90% band {band(f['c_low'], f['c_high'])}."]
        else:
            L += factor_table(k["factors"], "c")
        ct = k["continuity"]
        L += [
            "",
            f"Continuity at the switch ({ct['window'][0]} to {ct['window'][1]}, out of sample): step index "
            f"{ct['step_index']:.3f}, band {band(*ct['band'])}, {'**flagged**' if ct['step_flagged'] else 'no step'}.",
        ]

    L += [
        "",
        "## Cross-check with the frontend/backend (2026-11-14)",
        "The teammate repo (`klol120/nasa-harmonization`, local branch `contract-0.5`) loads these exports",
        "unchanged and passes every contract invariant check. It never recomputes harmonized values. For",
        "every region, its yearly totals, peak month, record year, monthly values and recomputed area z",
        "match the values recomputed from `data/processed/{region}/harmonized.parquet` to within",
        "5e-5 (the API's 4-decimal rounding).",
        "",
        f"Source commit: `{head}` (before this file was added). Holdout and continuity tables:",
        "`docs/reports/{region}_validation.md` and `docs/reports/{region}_continuation.md`.",
        "",
    ]
    out = ROOT / "docs/FINAL_RATIOS.md"
    out.write_text("\n".join(L), encoding="utf-8")
    print(f"wrote {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
